#!/bin/sh
# LLMule installer for macOS and Linux. https://llmule.xyz
#
#   curl -fsSL https://llmule.xyz/install | sh
#   curl -fsSL https://llmule.xyz/install | sh -s -- --lang en     (arguments after -- go to llmule)
#
# Downloads the one LLMule binary for this machine, checks its sha256 against the list in this script,
# puts it in ~/.llmule/bin/llmule and opens it. No sudo; nothing is written outside ~/.llmule.
# Remove it: ~/.llmule/bin/llmule --uninstall, then delete ~/.llmule.
#
# Env: LLMULE_HOME   where LLMule lives (default ~/.llmule; the app reads it too)
#      LLMULE_NO_RUN=1  install only, don't open it
#
# Source (MIT): https://github.com/andycufari/llmule
# This file is generated by installer/tools/gen-install.mjs from install.sh.tmpl: edit the template.

set -eu

VERSION='0.2.3-test'
BASE='https://cm64-ss-public.s3.amazonaws.com/67608172a31516c083602958/installer'

# The sha256 of each binary of this version. They come from SHA256SUMS when the script is generated:
# the script is the root of trust, so a swapped binary on the download server doesn't pass.
sum_for() {
  case "$1" in
    mac-arm64) echo '4c4d4fb677fd41992c15d03f4ca94cbaeb41c509bc07cc964bcd6969813ba406' ;;
    mac-x64) echo '654926128ed39b725e1212f530a89c7b4c14d7c21fde25f3d262aca1a459ed30' ;;
    linux-x64) echo 'fcfb89160ae6f526fae88c3db478c6814f252d51d621618d0c5aa901f68b831f' ;;
    linux-arm64) echo '9b39af812dc5f7c8b628d81685a573bbb624a32f977865c129f8e32d4a668f04' ;;
    *) echo '' ;;
  esac
}

ES=0
case "${LC_ALL:-${LC_MESSAGES:-${LANG:-}}}" in es*) ES=1 ;; esac

# say "english" "castellano"
say() { if [ "$ES" = 1 ]; then printf '%s\n' "$2"; else printf '%s\n' "$1"; fi; }
fail() {
  if [ "$ES" = 1 ]; then printf 'llmule: %s\n' "$2" >&2; else printf 'llmule: %s\n' "$1" >&2; fi
  exit 1
}
has() { command -v "$1" >/dev/null 2>&1; }

unsupported() {
  fail "LLMule doesn't run on $1 yet. Tell me on Discord: https://discord.gg/uM8fFz56YB" \
       "LLMule todavía no corre en $1. Contame en Discord: https://discord.gg/uM8fFz56YB"
}

target() {
  os=$(uname -s)
  arch=$(uname -m)
  case "$os" in
    Darwin)
      case "$arch" in
        arm64) echo mac-arm64 ;;
        x86_64)
          # A shell under Rosetta says x86_64 on Apple Silicon: the native binary is the right one
          if [ "$(sysctl -n sysctl.proc_translated 2>/dev/null || echo 0)" = 1 ]; then echo mac-arm64; else echo mac-x64; fi ;;
        *) unsupported "macOS $arch" ;;
      esac ;;
    Linux)
      if [ "$(getconf LONG_BIT 2>/dev/null || echo 64)" = 32 ]; then unsupported "32-bit Linux ($arch)"; fi
      if ldd --version 2>&1 | grep -qi musl; then
        fail "this Linux uses musl (Alpine?). LLMule needs glibc 2.27 or newer (Ubuntu 18.04+, Debian 10+, Fedora...)." \
             "este Linux usa musl (¿Alpine?). LLMule necesita glibc 2.27 o más nuevo (Ubuntu 18.04+, Debian 10+, Fedora...)."
      fi
      v=$(getconf GNU_LIBC_VERSION 2>/dev/null | sed -n 's/^glibc \([0-9][0-9]*\.[0-9][0-9]*\).*/\1/p')
      if [ -n "$v" ]; then
        maj=${v%%.*}; min=${v#*.}
        if [ "$maj" -lt 2 ] || { [ "$maj" -eq 2 ] && [ "$min" -lt 27 ]; }; then
          fail "LLMule needs glibc 2.27 or newer; this machine has $v." \
               "LLMule necesita glibc 2.27 o más nuevo; esta máquina tiene $v."
        fi
      fi
      case "$arch" in
        x86_64 | amd64) echo linux-x64 ;;
        aarch64 | arm64) echo linux-arm64 ;;
        *) unsupported "Linux $arch" ;;
      esac ;;
    MINGW* | MSYS* | CYGWIN*)
      fail "on Windows, open PowerShell and run: irm https://llmule.xyz/install.ps1 | iex" \
           "en Windows, abrí PowerShell y corré: irm https://llmule.xyz/install.ps1 | iex" ;;
    *) unsupported "$os $arch" ;;
  esac
}

download() { # url file
  if has curl; then
    curl -fL --proto '=https' --tlsv1.2 --retry 3 --progress-bar -o "$2" "$1"
  elif has wget; then
    wget -q -O "$2" "$1"
  else
    fail "needs curl or wget." "hace falta curl o wget."
  fi
}

sha256_of() {
  if has sha256sum; then sha256sum "$1" | cut -d' ' -f1
  elif has shasum; then shasum -a 256 "$1" | cut -d' ' -f1
  elif has openssl; then openssl dgst -sha256 "$1" | sed 's/.*= *//'
  else fail "needs sha256sum, shasum or openssl to check the download." \
            "hace falta sha256sum, shasum u openssl para verificar la descarga."
  fi
}

main() {
  : "${HOME:?}"
  has curl || has wget || fail "needs curl or wget." "hace falta curl o wget."
  t=$(target)
  want=$(sum_for "$t")
  [ -n "$want" ] || unsupported "$t"

  root=${LLMULE_HOME:-$HOME/.llmule}
  dir=$root/bin
  bin=$dir/llmule
  case "$bin" in "$HOME"/*) shown="~${bin#"$HOME"}" ;; *) shown=$bin ;; esac
  file="llmule-$VERSION-$t"

  say "LLMule $VERSION for $t" "LLMule $VERSION para $t"
  mkdir -p "$dir"
  tmp=$(mktemp "$dir/.llmule-download.XXXXXX")
  trap 'rm -f "$tmp"' EXIT
  trap 'rm -f "$tmp"; exit 130' INT TERM

  download "$BASE/$file" "$tmp" || fail "couldn't download $BASE/$file" "no pude bajar $BASE/$file"
  got=$(sha256_of "$tmp")
  if [ "$got" != "$want" ]; then
    rm -f "$tmp"
    fail "the download doesn't match its sha256 (got $got). Nothing was installed." \
         "lo que bajé no coincide con su sha256 (dio $got). No instalé nada."
  fi
  chmod 755 "$tmp"
  mv -f "$tmp" "$bin"
  trap - EXIT INT TERM

  if ! "$bin" --version >/dev/null 2>&1; then
    fail "installed $shown, but it doesn't start on this machine. Tell me on Discord: https://discord.gg/uM8fFz56YB" \
         "instalé $shown, pero no arranca en esta máquina. Contame en Discord: https://discord.gg/uM8fFz56YB"
  fi
  say "sha256 OK. Installed in $shown" "sha256 OK. Instalado en $shown"

  # curl | sh leaves stdin on the pipe: the full-screen app needs the keyboard, so it reads /dev/tty
  if [ -z "${LLMULE_NO_RUN:-}" ] && [ -t 1 ] && (: </dev/tty) 2>/dev/null; then
    say "Opening LLMule..." "Abriendo LLMule..."
    exec "$bin" "$@" </dev/tty
  fi
  say "Next: run $shown (it links your llmule.xyz account and starts sharing)." \
      "Próximo paso: corré $shown (vincula tu cuenta de llmule.xyz y empieza a compartir)."
}

# Everything runs from here, so a download cut halfway never runs half a script
main "$@"
