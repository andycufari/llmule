#!/usr/bin/env node
// Builds the one-line installers from their templates, with the sha256 of each binary taken from dist/SHA256SUMS:
//   install/install.sh    curl -fsSL https://llmule.xyz/install | sh
//   install/install.ps1   irm https://llmule.xyz/install.ps1 | iex
// and, with --functions <dir>, the two CM64 functions that serve them as text/plain on llmule.xyz
// (function/muleInstallSh.js for /install and /install.sh, function/muleInstallPs1.js for /install.ps1).
//
//   node tools/gen-install.mjs [--version 0.2.3-test] [--base s3|github|<url>] [--functions <dir>]
//
// --version  which binaries (default: lib/version.mjs). They must all be in dist/SHA256SUMS.
// --base     where the binaries are downloaded from. s3 (default) = the CM64 bucket llmule.xyz already uses;
//            github = the release v<version> of andycufari/llmule (it has to exist first).
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const TARGETS = ['mac-arm64', 'mac-x64', 'linux-x64', 'linux-arm64', 'windows-x64.exe'];
const S3 = 'https://cm64-ss-public.s3.amazonaws.com/67608172a31516c083602958/installer';

const arg = (name) => {
  const i = process.argv.indexOf(`--${name}`);
  return i > 0 ? process.argv[i + 1] : undefined;
};

const version = arg('version') || fs.readFileSync(path.join(ROOT, 'lib/version.mjs'), 'utf8').match(/VERSION = '([^']+)'/)[1];
const baseArg = arg('base') || 's3';
const base = baseArg === 's3' ? S3
  : baseArg === 'github' ? `https://github.com/andycufari/llmule/releases/download/v${version}`
  : baseArg.replace(/\/+$/, '');
if (!/^https:\/\//.test(base)) throw new Error(`--base has to be https: ${base}`);

const sums = {};
for (const line of fs.readFileSync(path.join(ROOT, 'dist/SHA256SUMS'), 'utf8').split('\n')) {
  const m = line.match(/^([0-9a-f]{64})\s+\*?(\S+)$/);
  if (m) sums[m[2]] = m[1];
}

const fill = (tmpl) => {
  let out = tmpl.replaceAll('@VERSION@', version).replaceAll('@BASE@', base);
  for (const t of TARGETS) {
    const file = `llmule-${version}-${t}`;
    if (!sums[file]) throw new Error(`${file} is not in dist/SHA256SUMS`);
    out = out.replaceAll(`@SUM_${t}@`, sums[file]);
  }
  const left = out.match(/@[A-Z_a-z0-9.-]+@/);
  if (left) throw new Error(`placeholder left: ${left[0]}`);
  return out;
};

const dir = path.join(ROOT, 'install');
const sh = fill(fs.readFileSync(path.join(dir, 'install.sh.tmpl'), 'utf8'));
const ps1 = fill(fs.readFileSync(path.join(dir, 'install.ps1.tmpl'), 'utf8'));
fs.writeFileSync(path.join(dir, 'install.sh'), sh, { mode: 0o755 });
fs.writeFileSync(path.join(dir, 'install.ps1'), ps1);
console.log(`install.sh + install.ps1: ${version} from ${base}`);

// The CM64 sandbox scans the raw function source (strings included) for these: the scripts must not trip them
const FORBIDDEN = [/\.constructor(?![a-zA-Z0-9_])/, /\.__proto__/, /\beval\s*\(/, /\bFunction\s*\(/, /import\s*\(/,
  /\brequire\s*\(/, /\bprocess\s*\./, /\bglobal\s*\./, /\bglobalThis\s*\./, /\bReflect\s*\./, /\bProxy\s*\(/,
  /\bWebAssembly\s*\./, /Object\s*\.\s*(getPrototypeOf|setPrototypeOf|getOwnPropertyDescriptor|defineProperty)/];

const fn = (name, route, script) => {
  const src = `// @desc GET ${route}: the LLMule one-line installer, as text/plain. GENERATED by installer/tools/gen-install.mjs (${version}): don't edit here, edit the template and regenerate
var SCRIPT = ${JSON.stringify(script)};

async function ${name}(app) {
  return app.response(SCRIPT, 200, { contentType: 'text/plain; charset=utf-8' });
}
`;
  const bad = FORBIDDEN.find((re) => re.test(src));
  if (bad) throw new Error(`${name}: the CM64 function validator would reject it (${bad})`);
  return src;
};

const out = arg('functions');
if (out) {
  fs.mkdirSync(out, { recursive: true });
  fs.writeFileSync(path.join(out, 'muleInstallSh.js'), fn('muleInstallSh', '/install, /install.sh', sh));
  fs.writeFileSync(path.join(out, 'muleInstallPs1.js'), fn('muleInstallPs1', '/install.ps1', ps1));
  console.log(`functions: ${out}/muleInstallSh.js, muleInstallPs1.js`);
}
