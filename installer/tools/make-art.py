#!/usr/bin/env python3
"""Dev-only: turn the mascot PNG into half-block pixel art for the TUI (lib/mule-art.mjs).

Each terminal cell shows two pixels stacked (the upper-half block, fg = top, bg = bottom), so an
image W px wide and H px tall takes W columns and H/2 rows. Transparent pixels stay '.' so the TUI
paints them with whatever is behind.

The source (brand/body-512.png) is itself pixel art at ~4 px per art pixel, so a plain resize turns it
into noise. Instead:
  1. every source pixel snaps to one of a few fixed colors (outline navy, two blues, body, highlight, green)
  2. each target pixel takes the majority color of its block, except that outline wins when it covers
     half the block (keeps the line work) and the green lights win at a smaller share (they're tiny)
  3. clean-up: lonely pixels go, the whole silhouette gets a navy outline, lone navy specks inside
     the body take their neighbours' color
No dithering, no gradients: 6 colors. The avatar colors are hue shifts of this same sprite (ui.hueShift).

    python3 -I tools/make-art.py      # run from installer/, rewrites lib/mule-art.mjs
"""
import json
import os
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = os.path.join(HERE, '..', '..', 'brand', 'body-512.png')
OUT = os.path.join(HERE, '..', 'lib', 'mule-art.mjs')

# What source pixels snap to (measured on the PNG) → what the TUI paints
SNAP = {
    'N': ((0, 26, 99), '#0a1f66'),      # outline
    'B': ((36, 97, 172), '#2461ac'),    # blue
    'L': ((90, 150, 205), '#5a96cd'),   # light blue
    'G': ((208, 202, 192), '#ece7dd'),  # body: lighter than the window gray (#d4d0c8), or it disappears
    'W': ((245, 243, 238), '#ffffff'),  # highlight
    'E': ((40, 190, 60), '#3fbf4f'),    # the green lights on the pack
}
ORDER = 'NBLGWE'

# name, width in px (= columns). Height follows the image (rows = height / 2).
SPECS = [('BODY', 34), ('MINI', 26)]
OUTLINE = 0.5   # share of a block that has to be outline for the pixel to be outline
GREEN = 0.18
N4 = ((1, 0), (-1, 0), (0, 1), (0, -1))


def nearest(rgb):
    return min(SNAP, key=lambda k: sum((a - b) ** 2 for a, b in zip(SNAP[k][0], rgb)))


def classes():
    im = Image.open(SRC).convert('RGBA')
    im = im.crop(im.getbbox())
    px = im.load()
    return [['.' if px[x, y][3] < 128 else nearest(px[x, y][:3]) for x in range(im.width)] for y in range(im.height)]


def downsample(cls, width):
    H, W = len(cls), len(cls[0])
    sx = W / width
    height = round(H / sx)
    height += height % 2
    sy = H / height
    rows = []
    for ty in range(height):
        row = ''
        for tx in range(width):
            cnt = {}
            for y in range(int(ty * sy), min(H, max(int(ty * sy) + 1, int((ty + 1) * sy)))):
                for x in range(int(tx * sx), min(W, max(int(tx * sx) + 1, int((tx + 1) * sx)))):
                    cnt[cls[y][x]] = cnt.get(cls[y][x], 0) + 1
            tot = sum(cnt.values())
            op = tot - cnt.get('.', 0)
            if cnt.get('.', 0) * 2 > tot:
                row += '.'
            elif cnt.get('N', 0) >= OUTLINE * op:
                row += 'N'
            elif cnt.get('E', 0) >= GREEN * op:
                row += 'E'
            else:
                rest = {k: v for k, v in cnt.items() if k not in '.N'}
                row += max(rest, key=rest.get) if rest else 'N'
        rows.append(row)
    return rows


def clean(rows):
    h, w = len(rows), len(rows[0])
    at = lambda r, x, y: r[y][x] if 0 <= x < w and 0 <= y < h else '.'
    g = [list(r) for r in rows]
    for y in range(h):
        for x in range(w):
            if rows[y][x] != '.' and all(at(rows, x + dx, y + dy) == '.' for dx, dy in N4):
                g[y][x] = '.'
    rows = [''.join(r) for r in g]
    g = [list(r) for r in rows]
    for y in range(h):
        for x in range(w):
            if rows[y][x] not in '.E' and any(at(rows, x + dx, y + dy) == '.' for dx, dy in N4):
                g[y][x] = 'N'
    rows = [''.join(r) for r in g]
    g = [list(r) for r in rows]
    for y in range(h):
        for x in range(w):
            if rows[y][x] != 'N':
                continue
            nb = [at(rows, x + dx, y + dy) for dx in (-1, 0, 1) for dy in (-1, 0, 1) if dx or dy]
            if '.' in nb or sum(c == 'N' for c in nb) > 1:
                continue
            cnt = {}
            for c in nb:
                if c != 'N':
                    cnt[c] = cnt.get(c, 0) + 1
            g[y][x] = max(cnt, key=cnt.get)
    return [''.join(r) for r in g]


def main():
    cls = classes()
    keys = '0123456789abcdefghijklmnopqrstuvwxyz'
    out = ['// Generated by tools/make-art.py from projects/llmule/brand/body-512.png — do not edit by hand.',
           '// px: one string per pixel row, one char per pixel: "." transparent, else an index into palette.']
    for name, width in SPECS:
        rows = clean(downsample(cls, width))
        px = [''.join('.' if c == '.' else keys[ORDER.index(c)] for c in r) for r in rows]
        art = {'w': width, 'h': len(rows), 'palette': [SNAP[k][1] for k in ORDER], 'px': px}
        out.append(f'export const {name} = {json.dumps(art, indent=1)};')
    with open(OUT, 'w') as f:
        f.write('\n'.join(out) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
